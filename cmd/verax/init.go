// runInit implements `verax init <suite.yaml> -- <command...> [args...]`:
// connects to a live stdio server, discovers its tools, and writes a starter
// suite with a discovery case plus one commented call skeleton per tool.
func runInit(args []string, stdout, stderr io.Writer) int {
	fs := flag.NewFlagSet("verax init", flag.ContinueOnError)
	fs.SetOutput(stderr)
	timeout := fs.Int("timeout_ms", 15000, "startup + initialize budget")
	if err := fs.Parse(args); err != nil {
		return 2
	}
	rest := fs.Args()
	// flag parsing stops at the first positional, so a later "--" separator
	// survives in Args(); strip it wherever it appears
	filtered := make([]string, 0, len(rest))
	for _, a := range rest {
		if a != "--" {
			filtered = append(filtered, a)
		}
	}
	rest = filtered
	if len(rest) < 2 {
		fmt.Fprintln(stderr, "usage: verax init <suite.yaml> -- <server command> [args...]")
		fmt.Fprintln(stderr, "example: verax init tests/my.suite.yaml -- npx -y @scope/mcp-server")
		return 2
	}
	outPath := rest[0]
	command := rest[1:]

	// split command respecting simple quotes
	parts := splitCommandArgs(command)

	ctx := context.Background()
	cli, err := mcpclient.Connect(ctx, mcpclient.StdioConfig{
		Command: parts[0],
		Args:    parts[1:],
	}, mcpclient.Options{HandshakeTimeout: time.Duration(*timeout) * time.Millisecond})
	if err != nil {
		fmt.Fprintf(stderr, "verax init: connect: %v\n", err)
		return 1
	}
	defer func() { _ = cli.Close() }()

	info := cli.InitializeResult()
	tools, err := cli.ListTools(ctx)
	if err != nil {
		fmt.Fprintf(stderr, "verax init: tools/list: %v\n", err)
		return 1
	}

	names := make([]string, 0, len(tools.Tools))
	for _, t := range tools.Tools {
		names = append(names, t.Name)
	}
	sort.Strings(names)

	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by `verax init` — edit expectations to match your server.\n")
	fmt.Fprintf(&b, "# Run: verax test %s\n", filepath.Base(outPath))
	fmt.Fprintf(&b, "suite: %s\n", suiteStem(outPath))
	fmt.Fprintf(&b, "target:\n")
	fmt.Fprintf(&b, "  command: %s\n", quoteCommand(parts))
	fmt.Fprintf(&b, "  timeout_startup_ms: %d\n", *timeout)
	fmt.Fprintf(&b, "# server: %s %s (protocol %s)\n", info.ServerInfo.Name, info.ServerInfo.Version, info.ProtocolVersion)
	fmt.Fprintf(&b, "case:\n")
	fmt.Fprintf(&b, "  - name: tool catalogue\n")
	fmt.Fprintf(&b, "    expect:\n")
	fmt.Fprintf(&b, "      tools.list.includes: [%s]\n", strings.Join(names, ", "))
	if len(names) > 0 {
		fmt.Fprintf(&b, "      tools.list.count: %d\n", len(names))
	}
	fmt.Fprintf(&b, "      tools.list.schema_valid: true\n")

	// Call skeletons are emitted COMMENTED: the generated suite passes out
	// of the box (discovery + leak); users uncomment per tool as they fill
	// the TODO placeholders — no red-first onboarding.
	for _, t := range tools.Tools {
		args := starterArgs(t)
		fmt.Fprintf(&b, "\n  # TODO: fill placeholders and uncomment — %s\n", oneLine(t.Description))
		fmt.Fprintf(&b, "  #- name: call %s\n", t.Name)
		fmt.Fprintf(&b, "  #  call: %s\n", t.Name)
		if len(args) > 0 {
			fmt.Fprintf(&b, "  #  args:\n")
			keys := make([]string, 0, len(args))
			for k := range args {
				keys = append(keys, k)
			}
			sort.Strings(keys)
			for _, k := range keys {
				fmt.Fprintf(&b, "  #    %s: %q\n", k, args[k])
			}
		}
		fmt.Fprintf(&b, "  #  expect:\n")
		fmt.Fprintf(&b, "  #    ok: true\n")
	}
	fmt.Fprintf(&b, "leak:\n  process_exit: true\n")

	if err := os.WriteFile(outPath, []byte(b.String()), 0o644); err != nil {
		fmt.Fprintf(stderr, "verax init: write: %v\n", err)
		return 1
	}
	// verify the generated suite parses
	if _, err := dsl.Parse([]byte(b.String()), outPath); err != nil {
		fmt.Fprintf(stderr, "verax init: generated suite invalid (bug): %v\n", err)
		return 1
	}
	fmt.Fprintf(stdout, "wrote %s (%d tools: %s)\nnext: verax test %s\n", outPath, len(names), strings.Join(names, ", "), outPath)
	return 0
}

// starterArgs builds benign placeholder arguments from the tool schema.
func starterArgs(t mcpclient.Tool) map[string]string {
	if len(t.InputSchema) == 0 {
		return nil
	}
	var schema struct {
		Properties map[string]struct {
			Type string `json:"type"`
		} `json:"properties"`
	}
	if err := json.Unmarshal(t.InputSchema, &schema); err != nil || len(schema.Properties) == 0 {
		return nil
	}
	out := map[string]string{}
	for name, p := range schema.Properties {
		switch p.Type {
		case "number", "integer":
			out[name] = "1"
		case "boolean":
			out[name] = "true"
		default:
			out[name] = "TODO"
		}
	}
	return out
}

func oneLine(s string) string {
	s = strings.TrimSpace(s)
	if i := strings.IndexByte(s, '\n'); i >= 0 {
		s = s[:i]
	}
	if len(s) > 70 {
		s = s[:70] + "…"
	}
	if s == "" {
		s = "(no description)"
	}
	return s
}

func suiteStem(path string) string {
	base := filepath.Base(path)
	base = strings.TrimSuffix(base, filepath.Ext(base))
	return strings.ToLower(strings.ReplaceAll(base, " ", "-"))
}

func quoteCommand(parts []string) string {
	quoted := make([]string, 0, len(parts))
	for _, p := range parts {
		if strings.ContainsAny(p, " \t") {
			quoted = append(quoted, "\""+p+"\"")
		} else {
			quoted = append(quoted, p)
		}
	}
	return strings.Join(quoted, " ")
}

func splitCommandArgs(command []string) []string {
	var out []string
	for _, p := range command {
		out = append(out, strings.Split(p, " ")...)
	}
	return out
}
