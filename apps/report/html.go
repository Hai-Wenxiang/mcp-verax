package report

import (
	"fmt"
	"strings"
)

// RenderHTML writes the report as a single self-contained page, styled to
// match the leaderboard (inline CSS, no JS), with a back-link to it.
func (r *Report) RenderHTML() string {
	var b strings.Builder
	b.WriteString(`<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Verax Ecosystem Report</title>
<style>
  :root { --pass:#1a7f37; --mid:#9a6700; --low:#cf222e; --crit:#82071e; --ink:#1f2328; --dim:#656d76; --bg:#f6f8fa; }
  body { font:14px/1.5 -apple-system,"Segoe UI","PingFang SC","Microsoft YaHei",sans-serif; color:var(--ink); margin:0; background:var(--bg); }
  header { background:#24292f; color:#fff; padding:22px 28px; }
  header h1 { margin:0 0 4px; font-size:18px; }
  header p { margin:0; color:#afb8c1; font-size:12px; }
  header a { color:#afb8c1; }
  main { max-width:900px; margin:0 auto; padding:20px; }
  section { background:#fff; border:1px solid #d0d7de; border-radius:8px; padding:14px 18px; margin-bottom:18px; }
  h2 { font-size:14px; margin:0 0 8px; color:var(--dim); }
  table { width:100%; border-collapse:collapse; font-size:13px; }
  th, td { text-align:left; padding:6px 8px; border-bottom:1px solid #eaeef2; }
  th { color:var(--dim); font-weight:600; font-size:12px; }
  td.n, th.n { text-align:right; }
  code { background:var(--bg); padding:1px 5px; border-radius:4px; font-size:12px; }
  .sev-critical { color:var(--crit); font-weight:700; }
  .sev-high { color:var(--low); font-weight:600; }
  .sev-medium { color:var(--mid); }
  .sev-low { color:var(--dim); }
  .delta-up { color:var(--pass); font-weight:700; }
  .delta-down { color:var(--low); font-weight:700; }
  .note { color:var(--dim); font-style:italic; }
  footer { text-align:center; color:var(--dim); font-size:12px; padding:14px; }
</style>
</head>
<body>
<header>
  <h1>Verax Ecosystem Report / 生态报告</h1>
  <p>aggregated from registry pulses · <a href="index.html">← leaderboard</a></p>
</header>
<main>
`)

	fmt.Fprintf(&b, "<section><h2>Snapshot / 快照</h2><p>As of <strong>%s</strong> · %s · <strong>%d</strong> unique packages · mean score <strong>%.1f</strong></p></section>\n",
		r.AsOf, r.span(), r.Packages, r.MeanScore)

	b.WriteString(`<section><h2>Score distribution (latest pulse per package)</h2><table><tr><th>Band</th><th class="n">Packages</th></tr>`)
	for _, label := range r.BandOrder {
		fmt.Fprintf(&b, "<tr><td>%s</td><td class=\"n\">%d</td></tr>", label, r.Bands[label])
	}
	b.WriteString(`</table></section>` + "\n")

	fmt.Fprintf(&b, `<section><h2>Findings by severity (all pulses)</h2><p>total <strong>%d</strong> — `, r.TotalFindings)
	for _, sev := range []string{"critical", "high", "medium", "low"} {
		fmt.Fprintf(&b, `<span class="sev-%s">%s %d</span> · `, sev, sev, r.SevCounts[sev])
	}
	b.WriteString(`</p></section>` + "\n")

	b.WriteString(`<section><h2>Most prevalent rules</h2><table><tr><th>Rule</th><th>Severity</th><th class="n">Hits</th></tr>`)
	for _, st := range r.TopRules {
		fmt.Fprintf(&b, `<tr><td><code>%s</code> %s</td><td class="sev-%s">%s</td><td class="n">%d</td></tr>`, st.ID, st.Title, st.Severity, st.Severity, st.Count)
	}
	b.WriteString(`</table></section>` + "\n")

	b.WriteString(`<section><h2>Riskiest packages</h2><table><tr><th>Package</th><th class="n">Score</th><th class="n">crit/high</th></tr>`)
	for _, ps := range r.Riskiest {
		fmt.Fprintf(&b, `<tr><td><code>%s</code></td><td class="n">%d</td><td class="n">%d/%d</td></tr>`, ps.Package, ps.Score, ps.Critical, ps.High)
	}
	b.WriteString(`</table></section>` + "\n")

	b.WriteString(`<section><h2>Trend (packages with ≥2 pulses)</h2>`)
	if len(r.Trend) == 0 {
		b.WriteString(`<p class="note">Needs more nightly pulses — movement appears from the second pulse date.</p>`)
	} else {
		b.WriteString(`<table><tr><th>Package</th><th class="n">first → last</th><th class="n">Δ</th></tr>`)
		for _, t := range r.Trend {
			cls := "delta-up"
			if t.Delta < 0 {
				cls = "delta-down"
			}
			fmt.Fprintf(&b, `<tr><td><code>%s</code></td><td class="n">%d → %d</td><td class="n %s">%+d</td></tr>`, t.Pkg, t.First, t.Last, cls, t.Delta)
		}
		b.WriteString(`</table>`)
	}
	b.WriteString(`</section>` + "\n")

	b.WriteString(`</main>
<footer>Generated by <code>verax report</code> · source pulses in the repo under <code>docs/registry/</code></footer>
</body>
</html>
`)
	return b.String()
}
